import { readFileSync } from "node:fs";

const source = new URL("../src/design/palette.json", import.meta.url);

/** @type {{ colors: Record<string, string>, themes: Record<string, { scheme: string, roles: Record<string, string> }> }} */
export const palette = JSON.parse(readFileSync(source, "utf8"));

/** Resolves a role of a theme, like dark/ground, to its hex value. */
export function role(theme, name) {
  const key = palette.themes[theme]?.roles[name];
  if (!key) throw new Error(`palette.json has no role ${theme}/${name}`);

  const value = palette.colors[key];
  if (!value) throw new Error(`palette.json has no colour named ${key}`);

  return value;
}

/** The literals index.html needs before any stylesheet has loaded. */
export const htmlColors = {
  groundLight: role("light", "ground"),
  groundDark: role("dark", "ground"),
};

export function paletteCss() {
  const tokens = Object.entries(palette.colors)
    .map(([name, value]) => `  --color-${name}: ${value};`)
    .join("\n");

  const themes = Object.entries(palette.themes)
    .map(([name, theme]) => {
      const selector = name === "light" ? ":root" : `.${name}`;
      const roles = Object.entries(theme.roles)
        .map(([key, color]) => `    --${key}: var(--color-${color});`)
        .join("\n");

      return `  ${selector} {\n    color-scheme: ${theme.scheme};\n${roles}\n  }`;
    })
    .join("\n\n");

  return `/* Autogenerated from src/design/palette.json. */\n@theme {\n${tokens}\n}\n\n@layer base {\n${themes}\n}\n`;
}
